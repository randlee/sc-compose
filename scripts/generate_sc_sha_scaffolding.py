#!/usr/bin/env python3
"""Generate or verify sc-sha's checked-in UniFFI Rust scaffolding."""

from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import tempfile

VERSION = "uniffi-bindgen 0.31.2"
HEADER = b"// Generated by UniFFI 0.31.2; do not edit by hand.\n"
ROOT = Path(__file__).resolve().parent.parent
UDL = ROOT / "bindings/sc-sha-go/src/sc_sha_go.udl"
OUTPUT = ROOT / "bindings/sc-sha-go/src/sc_sha_go.uniffi.rs"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("write", "check"), default="write")
    args = parser.parse_args()
    version = subprocess.run(
        ["uniffi-bindgen", "--version"], check=True, capture_output=True, text=True
    ).stdout.strip()
    if version != VERSION:
        parser.error(f"expected {VERSION}; found {version}")
    with tempfile.TemporaryDirectory(prefix="sc-sha-scaffolding-") as temp:
        subprocess.run(
            ["uniffi-bindgen", "scaffolding", "--no-format", "--out-dir", temp, str(UDL)],
            check=True,
        )
        generated = HEADER + (Path(temp) / OUTPUT.name).read_bytes()
    if args.mode == "check":
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != generated:
            print(f"generated scaffolding differs: {OUTPUT}")
            return 1
        print(f"generated scaffolding matches: {OUTPUT}")
    else:
        OUTPUT.write_bytes(generated)
        print(f"generated scaffolding written: {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
